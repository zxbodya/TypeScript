import * as ts from "../../_namespaces/ts.js";
import {
    FakePnpApi,
    getPnpMonorepoFiles,
    getPnpMonorepoPackages,
    PnpPackage,
    pnpPaths,
    pnpProjectRoot,
    useFakePnpApi,
} from "../helpers/pnp.js";
import { TestServerHost } from "../helpers/virtualFileSystemWithWatch.js";

describe("unittests:: tsbuildWatch:: pnp::", () => {
    let api: FakePnpApi;
    useFakePnpApi(() => api = new FakePnpApi(pnpProjectRoot, getPnpMonorepoPackages()));

    const fooV2Location = `${pnpProjectRoot}/.yarn/cache/foo-npm-2.0.0.zip/node_modules/foo`;

    function withAppDependency(name: string, reference: string): PnpPackage[] {
        return [
            ...getPnpMonorepoPackages().map(pkg =>
                pkg.name === "app"
                    ? { ...pkg, dependencies: { ...pkg.dependencies, [name]: reference } }
                    : pkg
            ),
            { name: "foo", reference: "npm:2.0.0", location: fooV2Location },
        ];
    }

    function build(appIndexContent: string) {
        const sys = TestServerHost.createWatchedSystem({
            ...getPnpMonorepoFiles(),
            [`${pnpPaths.app}/tsconfig.json`]: JSON.stringify({
                compilerOptions: { composite: true, module: "esnext", moduleResolution: "bundler", strict: true, outDir: "dist" },
                include: ["src"],
            }),
            [pnpPaths.appIndex]: appIndexContent,
            [`${fooV2Location}/package.json`]: JSON.stringify({ name: "foo", version: "2.0.0", types: "index.d.ts" }),
            [`${fooV2Location}/index.d.ts`]: `export declare const fooValue: string;\n`,
        }, { currentDirectory: pnpPaths.app });
        let errorCodes: number[] = [];
        let program: ts.Program | undefined;
        const createProgram: ts.CreateProgram<ts.EmitAndSemanticDiagnosticsBuilderProgram> = (...args) => {
            const builderProgram = ts.createEmitAndSemanticDiagnosticsBuilderProgram(...args);
            program = builderProgram.getProgram();
            return builderProgram;
        };
        const host = ts.createSolutionBuilderWithWatchHost(sys, createProgram, d => errorCodes.push(d.code), ts.noop, ts.noop);
        const builder = ts.createSolutionBuilderWithWatch(host, [`${pnpPaths.app}/tsconfig.json`], {});
        builder.build();
        return {
            getErrorCodes: () => errorCodes,
            hasSourceFile: (fileName: string) => !!program!.getSourceFile(fileName),
            /** Simulates `yarn install` regenerating the PnP runtime with the given dependency tree; returns whether a new program got built. */
            install(packages: PnpPackage[]) {
                errorCodes = [];
                const previousProgram = program;
                api.setPackages(packages);
                sys.writeFile(api.pnpApiPath, "/* regenerated by yarn */");
                sys.runQueuedTimeoutCallbacks();
                return program !== previousProgram;
            },
        };
    }

    it("rebuilds when a missing dependency gets installed", () => {
        const { getErrorCodes, hasSourceFile, install } = build(`import { bazValue } from "baz";\nexport const value: number = bazValue;\n`);
        assert.deepEqual(getErrorCodes(), [ts.Diagnostics.Cannot_find_module_0_or_its_corresponding_type_declarations.code]);

        assert.isTrue(install(withAppDependency("baz", "npm:1.0.0")), "should rebuild");
        assert.isTrue(hasSourceFile(pnpPaths.bazIndex));
        assert.deepEqual(getErrorCodes(), []);
    });

    it("rebuilds up to date projects when a dependency is upgraded", () => {
        const { getErrorCodes, hasSourceFile, install } = build(`import { fooValue } from "foo";\nexport const value: number = fooValue;\n`);
        assert.deepEqual(getErrorCodes(), []);

        // foo@2 is installed at another location, and its `fooValue` is a string
        assert.isTrue(install(withAppDependency("foo", "npm:2.0.0")), "should rebuild");
        assert.isTrue(hasSourceFile(`${fooV2Location}/index.d.ts`));
        assert.isFalse(hasSourceFile(pnpPaths.fooIndex));
        assert.deepEqual(getErrorCodes(), [ts.Diagnostics.Type_0_is_not_assignable_to_type_1.code]);
    });
});
