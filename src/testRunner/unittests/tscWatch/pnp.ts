import * as ts from "../../_namespaces/ts.js";
import {
    FakePnpApi,
    getPnpMonorepoFiles,
    getPnpMonorepoPackages,
    pnpPaths,
    pnpProjectRoot,
    useFakePnpApi,
} from "../helpers/pnp.js";
import { TestServerHost } from "../helpers/virtualFileSystemWithWatch.js";

describe("unittests:: tscWatch:: pnp::", () => {
    let api: FakePnpApi;
    useFakePnpApi(() => api = new FakePnpApi(pnpProjectRoot, getPnpMonorepoPackages()));

    it("reloads module resolutions when the PnP runtime changes", () => {
        const sys = TestServerHost.createWatchedSystem({
            ...getPnpMonorepoFiles(),
            [pnpPaths.appIndex]: `import { bazValue } from "baz";\nexport const value = bazValue;\n`,
        }, { currentDirectory: pnpPaths.app });
        const host = ts.createWatchCompilerHost(`${pnpPaths.app}/tsconfig.json`, {}, sys, ts.createSemanticDiagnosticsBuilderProgram, ts.noop, ts.noop);
        const watch = ts.createWatchProgram(host);
        try {
            const getErrorCodes = () => ts.getPreEmitDiagnostics(watch.getProgram().getProgram()).map(d => d.code);
            assert.deepEqual(getErrorCodes(), [ts.Diagnostics.Cannot_find_module_0_or_its_corresponding_type_declarations.code]);

            // `yarn add baz` in the app workspace
            api.setPackages(
                getPnpMonorepoPackages().map(pkg =>
                    pkg.name === "app"
                        ? { ...pkg, dependencies: { ...pkg.dependencies, baz: "npm:1.0.0" } }
                        : pkg
                ),
            );
            sys.writeFile(api.pnpApiPath, "/* regenerated by yarn */");
            sys.runQueuedTimeoutCallbacks();

            assert.deepEqual(getErrorCodes(), []);
            assert.isDefined(watch.getProgram().getProgram().getSourceFile(pnpPaths.bazIndex));
        }
        finally {
            watch.close();
        }
    });
});
